#!/usr/bin/env node
/**
 * gen-migrations-module.mjs — build helper that embeds the SQL migrations into
 * a TypeScript module so the migration runner works inside serverless bundles.
 *
 * Why: the runner resolves `src/lib/db/migrations/` through the filesystem
 * (walking up from import.meta.url / process.cwd()). Next.js file-tracing only
 * follows JS imports, so on Vercel Functions the .sql files are not shipped and
 * every cold start crashes with "[Migration] Could not resolve migrations
 * directory. Set OMNIROUTE_MIGRATIONS_DIR." — taking the authz pipeline (and
 * every API route it wraps) down with it.
 *
 * The generated module (`src/lib/db/migrations/embedded.generated.ts`) carries
 * the exact filename + SQL content of every migration, sorted by filename —
 * identical semantics to the runner's readdirSync path. The runner prefers the
 * filesystem when the directory exists (Docker/npm/VPS installs are unchanged)
 * and falls back to the embedded set when it does not (serverless).
 *
 * The generated file is COMMITTED so `npm run dev` and non-prebuild paths work
 * without any generation step; `prebuild` (and `prebuild:fast`) regenerate it
 * so a build can never ship stale SQL. Mirrors gen-openapi-module.mjs.
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..", "..");
const MIGRATIONS_DIR = path.join(ROOT, "src", "lib", "db", "migrations");
const OUT_PATH = path.join(MIGRATIONS_DIR, "embedded.generated.ts");

const MIGRATION_FILE_PATTERN = /^(\d+)_(.+)\.sql$/;

async function main() {
  const entries = await fs.readdir(MIGRATIONS_DIR);
  const files = entries
    .filter((f) => f.endsWith(".sql") && MIGRATION_FILE_PATTERN.test(f))
    .sort();

  const chunks = [];
  for (const filename of files) {
    const sql = await fs.readFile(path.join(MIGRATIONS_DIR, filename), "utf-8");
    chunks.push(`  { filename: ${JSON.stringify(filename)}, sql: ${JSON.stringify(sql)} },`);
  }

  const banner = `// GENERATED by scripts/build/gen-migrations-module.mjs — DO NOT EDIT.
// Regenerated by \`prebuild\` from src/lib/db/migrations/*.sql (sorted by filename).
// Carried so the migration runner can apply the schema inside serverless
// bundles where the .sql files are not file-traced. See migrationRunner.ts.`;

  const body = `${banner}

export interface EmbeddedMigration {
  /** Exact migration filename, e.g. "001_initial_schema.sql". */
  filename: string;
  /** Full SQL content of the file. */
  sql: string;
}

export const EMBEDDED_MIGRATIONS: ReadonlyArray<EmbeddedMigration> = [
${chunks.join("\n")}
];
`;

  await fs.writeFile(OUT_PATH, body, "utf-8");
  console.log(
    `[gen-migrations-module] embedded ${files.length} migrations (${files.length} entries) -> ${path.relative(ROOT, OUT_PATH)}`
  );
}

main().catch((err) => {
  console.error(`[gen-migrations-module] failed: ${err?.message ?? err}`);
  process.exit(1);
});
